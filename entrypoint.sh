#!/bin/sh
set -e

# Railway монтирует Volume от имени root.
# Наш скрипт запускается от root, чтобы иметь право сменить владельца папки.
if [ "$(id -u)" = "0" ]; then
    DATA_DIR="/data"
    mkdir -p "$DATA_DIR"
    # Меняем владельца папки на пользователя 1000 (UID бота)
    chown -R 1000:1000 "$DATA_DIR" || true
    # Переключаемся на этого пользователя и запускаем бота
    exec gosu 1000:1000 "$@"
fi

# Если скрипт запущен не от root, просто выполняем команду
exec "$@"